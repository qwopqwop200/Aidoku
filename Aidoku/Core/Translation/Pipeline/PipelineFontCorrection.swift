/// S8 font px as layout reads it: the geometric `PipelineSimpleFont` size times exp(z + level), z the
/// letter-weighted median over the block's size group of a small LightGBM regression (100 trees, 4 leaves,
/// L1) of log(GT px / estimate) on line geometry, fit on TRAIN folds (`port-eval/fontsize-agent/export.py`).
/// One factor per group keeps grouped blocks equal (per-block factors split size families and broke
/// alignment). `level` keeps the rule's global level (it runs 2.8% high, TRAIN median), which the S9
/// sizing constants were fit to; only the relative error is corrected. Held-out median |error|
/// 4.3% -> 3.5% (dev), 4.7% -> 3.0% (test), share over 10%: 10.5% -> 7.7%, 11.2% -> 10.5%.
enum PipelineFontCorrection {
    static var level: Double { PipelineTuning.current.fontLevel }
    static func corrected(_ blocks: [PipelineBlock], fonts: [CGFloat], groups: [Int]) -> [CGFloat] {
        guard !blocks.isEmpty else { return fonts }
        let pageMedian = median(fonts.map(Double.init))
        let x = blocks.indices.map { features(blocks[$0], font: Double(fonts[$0]), pageMedian: pageMedian) }
        let z = x.map(forest.logit)
        var members: [Int: [Int]] = [:]
        for index in blocks.indices { members[groups[index], default: []].append(index) }
        var result = fonts
        for group in members.values {
            // Weighted median: the first value (ascending) whose cumulative weight reaches half.
            let sorted = group.sorted { z[$0] != z[$1] ? z[$0] < z[$1] : $0 < $1 }
            let weights = sorted.map { max(1, x[$0][9]) }
            let half = weights.reduce(0, +) / 2
            var cumulative = 0.0, factor = z[sorted[sorted.count - 1]]
            for (index, weight) in zip(sorted, weights) {
                cumulative += weight
                if cumulative >= half { factor = z[index]; break }
            }
            for index in group { result[index] = CGFloat(Double(fonts[index]) * exp(factor + level)) }
        }
        return result
    }

    static func median(_ values: [Double]) -> Double {
        guard !values.isEmpty else { return 0 }
        let sorted = values.sorted(), middle = sorted.count / 2
        return sorted.count % 2 == 1 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2
    }

    /// Line geometry relative to the estimate `font` (page px); `pageMedian` is the page's median estimate.
    static func features(_ block: PipelineBlock, font: Double, pageMedian: Double) -> [Double] {
        var shorts: [Double] = [], pitches: [Double] = [], confidences: [Double] = []
        for line in block.lines {
            let xs = line.polygon.map { Double($0.x) }, ys = line.polygon.map { Double($0.y) }
            let width = (xs.max() ?? 0) - (xs.min() ?? 0), height = (ys.max() ?? 0) - (ys.min() ?? 0)
            let (short, long) = block.vertical ? (width, height) : (height, width)
            let letters = max(1, line.text.unicodeScalars.filter { !$0.properties.isWhitespace }.count)
            shorts.append(short)
            pitches.append(long / Double(letters))
            confidences.append(Double(line.confidence))
        }
        let letters = block.sourceText.unicodeScalars.filter { !$0.properties.isWhitespace }.count
        return [font, median(shorts) / font, (shorts.max() ?? 0) / font, (shorts.min() ?? 0) / font,
                median(pitches) / font, (pitches.max() ?? 0) / font, Double(block.lines.count),
                block.vertical ? 1 : 0, font / pageMedian, Double(letters), block.balloon != nil ? 1 : 0,
                median(confidences)]
    }

