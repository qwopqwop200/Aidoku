prelude = '''// Generated by Scripts/overlay-kernels/native/generate-bindings.py. Kernel algorithms live only in kernels.rs.
import Foundation
import AidokuOverlayKernels

protocol NativeKernelElement: AdditiveArithmetic {}
extension UInt8: NativeKernelElement {}
extension Int32: NativeKernelElement {}
extension Float: NativeKernelElement {}
extension Double: NativeKernelElement {}

/// Zeroed, aligned scratch owned for the entire native call; pointers never escape this bridge.
final class NativeKernelBuffer<Element: NativeKernelElement> {
    let count: Int
    fileprivate let pointer: UnsafeMutablePointer<Element>
    private let retainedOwner: AnyObject?
    private let ownsStorage: Bool
    fileprivate var byteCount: Int { max(1, count) * MemoryLayout<Element>.stride }
    init(count: Int) throws {
        guard count >= 0, count <= (128 * 1_024 * 1_024) / MemoryLayout<Element>.stride else {
            throw NativeTranslationPixelKernels.KernelError.invalidBuffer
        }
        self.count = count
        retainedOwner = nil
        ownsStorage = true
        pointer = .allocate(capacity: max(1, count))
        pointer.initialize(repeating: .zero, count: max(1, count))
    }
    convenience init(values: [Element]) throws {
        try self.init(count: values.count)
        if !values.isEmpty { values.withUnsafeBufferPointer { pointer.update(from: $0.baseAddress!, count: values.count) } }
    }
    private init(pointer: UnsafeMutablePointer<Element>, count: Int, owner: AnyObject) {
        self.pointer = pointer; self.count = count; retainedOwner = owner; ownsStorage = false
    }
    /// Native kernels intentionally alias byte/Float32 scratch. The view retains its source allocation;
    /// offset, alignment and full byte extent are validated, and borrowed storage is never freed twice.
    func view<Other: NativeKernelElement>(as: Other.Type, byteOffset: Int, count: Int) throws -> NativeKernelBuffer<Other> {
        let capacity = self.count * MemoryLayout<Element>.stride
        guard byteOffset >= 0, byteOffset <= capacity, count >= 0,
              count <= (capacity - byteOffset) / MemoryLayout<Other>.stride else {
            throw NativeTranslationPixelKernels.KernelError.invalidBuffer
        }
        let bytes = UnsafeMutableRawPointer(pointer).advanced(by: byteOffset)
        guard UInt(bitPattern: bytes) % UInt(MemoryLayout<Other>.alignment) == 0 else {
            throw NativeTranslationPixelKernels.KernelError.invalidBuffer
        }
        return NativeKernelBuffer<Other>(pointer: bytes.assumingMemoryBound(to: Other.self), count: count, owner: self)
    }
    deinit { if ownsStorage { pointer.deinitialize(count: max(1, count)); pointer.deallocate() } }
    var values: [Element] { Array(UnsafeBufferPointer(start: pointer, count: count)) }
    subscript(index: Int) -> Element {
        get { precondition((0..<count).contains(index)); return pointer[index] }
        set { precondition((0..<count).contains(index)); pointer[index] = newValue }
    }
    fileprivate func require(_ minimum: Int) throws {
        guard minimum >= 0, count >= minimum else { throw NativeTranslationPixelKernels.KernelError.invalidBuffer }
    }
}

enum NativeTranslationPixelKernels {
    enum KernelError: Error { case invalidGeometry, invalidBuffer, invalidIndex, invalidScalar }
    static let exportedKernelCount = 25
    private static func checkedCount(_ value: Int32) throws -> Int {
        guard value >= 0, value <= 4_000_000 else { throw KernelError.invalidGeometry }
        return Int(value)
    }
    private static func pixelCount(_ width: Int32, _ height: Int32) throws -> Int {
        guard width > 0, height > 0, width <= 16_384, height <= 16_384,
              Int64(width) * Int64(height) <= 4_000_000 else { throw KernelError.invalidGeometry }
        return Int(width) * Int(height)
    }
    private static func indices(_ buffer: NativeKernelBuffer<Int32>, count: Int, pixels: Int) throws {
        try buffer.require(count)
        for index in 0..<count where buffer[index] < 0 || Int(buffer[index]) >= pixels { throw KernelError.invalidIndex }
    }
    private static func finite(_ buffer: NativeKernelBuffer<Double>, count: Int) throws {
        try buffer.require(count)
        for index in 0..<count where !buffer[index].isFinite { throw KernelError.invalidScalar }
    }
'''
header = ['// Generated from kernels.rs. Compile the same Rust source for native CPU and WASM.','#pragma once','#include <stdint.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif']
swift = [prelude]
for name, text, ret in functions:
    params=[]
    for item in text.split(','):
        label, typ = map(str.strip,item.split(':'))
        pointer = typ.startswith('*')
        base = typ.split()[-1] if pointer else typ
        params.append((label,typ,base,pointer))
    cparams = [f'{"const " if typ.startswith("*const") else ""}{ct[base]}{" *" if pointer else " "}{"aidoku_" + label}' for label,typ,base,pointer in params]
    header.append(f'{"int32_t" if ret.strip() else "void"} {name}({", ".join(cparams)});')
    sig = [f'{label}: NativeKernelBuffer<{st[base]}>' if pointer else f'{label}: {st[base]}' for label,typ,base,pointer in params]
    # Wrap lines deterministically for project line length policy.
    swift.append(f'    static func {name}(\n        '+',\n        '.join(sig)+f'\n    ) throws{ " -> Int32" if ret.strip() else ""} {{')
    labels={label for label,_,_,_ in params}
    if 'w' in labels and 'h' in labels: swift.append('        let n = try pixelCount(w, h)')
    elif name=='caption_exposed':
        swift.append('        guard w > 0, rgba.count % (Int(w)*4) == 0 else { throw KernelError.invalidGeometry }')
        swift.append('        let n = try pixelCount(w, Int32(rgba.count / (Int(w)*4)))')
    elif 'n' in labels: swift.append('        let n = try checkedCount(n)')
    elif 'count' in labels: swift.append('        let n = try checkedCount(count)')
    elif name=='columns_sum':
        swift.append('        guard from >= 0, to >= from else { throw KernelError.invalidGeometry }')
