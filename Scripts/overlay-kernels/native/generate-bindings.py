    swift.append('        let scratch: [AnyObject] = ['+', '.join(buffers)+']')
    swift.append('        let byteCost = ['+', '.join(label+'.byteCount' for label in buffers)+'].reduce(0, +)')
    swift.append('        guard byteCost <= 512 * 1_024 * 1_024 else { throw KernelError.invalidBuffer }')
